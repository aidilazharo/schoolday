@Composable fun LanguageMenu(lang:String,onChange:(String)->Unit){
    var expanded by remember{mutableStateOf(false)}
    Box{
        OutlinedButton(onClick={expanded=true},modifier=Modifier.fillMaxWidth()){Text(SchooldayLanguage.text("Language",lang)+" · "+(SchooldayLanguage.options.firstOrNull{it.first==lang}?.second?:"Bahasa Melayu"))}
        DropdownMenu(expanded=expanded,onDismissRequest={expanded=false}){
            SchooldayLanguage.options.forEach{(id,label)->DropdownMenuItem(text={Text(label)},onClick={expanded=false;onChange(id)})}
        }
    }
